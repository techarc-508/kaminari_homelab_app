package com.rplab.kaminarinfty.data.preferences

import android.content.Context
import android.security.keystore.KeyGenParameterSpec
import android.security.keystore.KeyProperties
import android.util.Base64
import java.security.KeyStore
import javax.crypto.Cipher
import javax.crypto.KeyGenerator
import javax.crypto.SecretKey
import javax.crypto.spec.GCMParameterSpec

/**
 * Secrets (ntfy access tokens / passwords) are encrypted with a hardware-backed
 * AES-GCM key in the Android Keystore before touching disk. The keystore never
 * exports the key; ciphertext + IV in SharedPreferences are useless off-device.
 *
 * Security properties relied on here:
 * - AES-256-GCM, 128-bit tag, random 12-byte IV generated by the provider.
 * - Key is generated in `AndroidKeyStore`, never leaves it, and is not
 *   exported to app memory as raw bytes.
 * - No custom TrustManager or HostnameVerifier exists anywhere in the client,
 *   so TLS always uses the platform trust chain.
 * - This class never logs values; failures return null instead of exposing data.
 */
interface SecretStore {
    fun put(key: String, secret: String)
    fun get(key: String): String?
    fun remove(key: String)
}

class KeystoreSecretStore(context: Context) : SecretStore {

    private val prefs = context.applicationContext
        .getSharedPreferences("kaminari_secrets", Context.MODE_PRIVATE)

    override fun put(key: String, secret: String) {
        require(secret.length <= MAX_SECRET_CHARS) { "Secret exceeds $MAX_SECRET_CHARS characters" }
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.ENCRYPT_MODE, getOrCreateKey())
        val ciphertext = cipher.doFinal(secret.toByteArray(Charsets.UTF_8))
        val payload = Base64.encodeToString(cipher.iv + ciphertext, Base64.NO_WRAP)
        prefs.edit().putString(key, payload).apply()
    }

    override fun get(key: String): String? = runCatching {
        val payload = prefs.getString(key, null) ?: return null
        val bytes = Base64.decode(payload, Base64.NO_WRAP)
        if (bytes.size <= IV_SIZE_BYTES) {
            prefs.edit().remove(key).apply()
            return null
        }
        val iv = bytes.copyOfRange(0, IV_SIZE_BYTES)
        val ciphertext = bytes.copyOfRange(IV_SIZE_BYTES, bytes.size)
        val cipher = Cipher.getInstance(TRANSFORMATION)
        cipher.init(Cipher.DECRYPT_MODE, getOrCreateKey(), GCMParameterSpec(TAG_BITS, iv))
        String(cipher.doFinal(ciphertext), Charsets.UTF_8)
    }.getOrElse {
        // Key invalidation or corrupt payload: drop it so the user is prompted
        // to re-enter credentials instead of looping on undecryptable data.
        prefs.edit().remove(key).apply()
        null
    }

    override fun remove(key: String) {
        prefs.edit().remove(key).apply()
    }

    /**
     * Key creation is synchronised because two concurrent encrypt/decrypt calls
     * could otherwise race and create two aliases.
     */
    @Synchronized
    private fun getOrCreateKey(): SecretKey {
        val keyStore = KeyStore.getInstance(KEYSTORE_PROVIDER).apply { load(null) }
        (keyStore.getEntry(KEY_ALIAS, null) as? KeyStore.SecretKeyEntry)?.let { return it.secretKey }

        val generator = KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, KEYSTORE_PROVIDER)
        generator.init(
            KeyGenParameterSpec.Builder(
                KEY_ALIAS,
                KeyProperties.PURPOSE_ENCRYPT or KeyProperties.PURPOSE_DECRYPT,
            )
                .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                .setKeySize(256)
                // Encryption must work while the user is using the app; no
                // biometric prompt is part of the V1 flow.
                .setUserAuthenticationRequired(false)
                .setRandomizedEncryptionRequired(true)
                .build()
        )
        return generator.generateKey()
    }

    private companion object {
        const val KEYSTORE_PROVIDER = "AndroidKeyStore"
        const val KEY_ALIAS = "kaminari-secrets-v1"
        const val TRANSFORMATION = "AES/GCM/NoPadding"
        const val TAG_BITS = 128
        const val IV_SIZE_BYTES = 12
        const val MAX_SECRET_CHARS = 4_096
    }
}
